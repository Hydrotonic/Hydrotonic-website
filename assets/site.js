// Scroll-linked effects, batched into one animation frame per scroll.
const tower = $('tower'), steps = document.querySelector('.steps'), band = document.querySelector('.band img');
const parts = tower && {
  draw: tower.querySelectorAll('.draw'), rise: tower.querySelectorAll('.rise'), drip: tower.querySelectorAll('.drip'),
  leaves: tower.querySelectorAll('.grow'), water: tower.querySelector('.water'), sun: tower.querySelector('.sun'),
  rays: tower.querySelector('.rays'), beam: tower.querySelector('.beam'), items: tower.querySelectorAll('.tw-step'), bar: tower.querySelector('.tw-bar i')
};
function renderTower(p) {
  // The tower draws in, the reservoir fills, the pump lifts water up the centre and over the top,
  // it trickles back down inside, and the leaves grow toward the sun.
  // Each group is only written when its value changed, so phones do the least work per frame.
  const draw = clamp(p / .35), fill = clamp((p - .28) / .1), rise = clamp((p - .36) / .18), drip = clamp((p - .52) / .08);
  if (draw !== seen.draw) { seen.draw = draw; parts.draw.forEach(el => { el.style.strokeDashoffset = 1 - draw; }); }
  if (fill !== seen.fill) { seen.fill = fill; parts.water.style.opacity = fill * .8; }
  if (rise !== seen.rise) { seen.rise = rise; parts.rise.forEach(el => { el.style.strokeDashoffset = 1 - rise; }); }
  parts.drip.forEach(el => { el.style.opacity = drip * .9; el.style.strokeDashoffset = -p * 240; });
  parts.sun.style.opacity = clamp(p / .15);
  parts.rays.style.transform = `rotate(${p * 90}deg)`;
  parts.beam.style.opacity = clamp((p - .45) / .2);
  parts.leaves.forEach((el, i) => { const g = clamp((p - .5 - i * (.3 / parts.leaves.length)) / .15); if (g !== seen.leaves[i]) { seen.leaves[i] = g; el.style.transform = `scale(${g})`; } });
  const active = Math.min(parts.items.length - 1, Math.floor(p * parts.items.length));
  if (active !== seen.active) { seen.active = active; parts.items.forEach((el, i) => el.classList.toggle('active', i === active)); }
  parts.bar.style.transform = `scaleX(${p})`;
}
const seen = { leaves: [] };
let ticking = false, lastP = -1;
// Header: slides away while scrolling down, comes back on any scroll up, always shown at the top.
// Small movements (under NAV_SLACK px) are ignored so it never flickers.
const nav = document.querySelector('.nav'), NAV_SLACK = 8;
let navY = scrollY;
function onNav() {
  const y = scrollY, d = y - navY;
  if (y <= (nav ? nav.offsetHeight : 80)) { document.body.classList.remove('nav-hidden'); navY = y; return; }
  if (Math.abs(d) < NAV_SLACK) return;
  // Keep it on screen while the visitor is using it (keyboard focus or an open language list).
  if (d > 0 && !(nav && nav.querySelector(':focus-visible'))) document.body.classList.add('nav-hidden');
  else if (d < 0) document.body.classList.remove('nav-hidden');
  navY = y;
}
if (nav) nav.addEventListener('focusin', () => { if (nav.querySelector(':focus-visible')) document.body.classList.remove('nav-hidden'); });
function onScroll() {
  document.body.classList.toggle('scrolled', scrollY > 140);
  onNav();
  if (reduced) return;
  // The drawing finishes one screen early; that last screen holds the finished tower before the page moves on.
  // Once drawn it stays drawn when scrolling back up; it only starts over after a return to the very top.
  // Only touch the DOM when something actually changed or is on screen.
  if (tower) {
    if (scrollY <= 0) lastP = -1;
    const r = tower.getBoundingClientRect(), p = Math.max(clamp(-r.top / (r.height - 2 * innerHeight)), lastP);
    if (p !== lastP) { lastP = p; renderTower(p); }
  }
  if (steps) { const r = steps.getBoundingClientRect(); if (r.bottom > 0 && r.top < innerHeight) steps.style.setProperty('--p', clamp((innerHeight * .75 - r.top) / r.height)); }
  if (band) { const r = band.parentElement.getBoundingClientRect(); if (r.bottom > 0 && r.top < innerHeight) band.style.transform = `translateY(${(r.top + r.height / 2 - innerHeight / 2) * -0.12}px)`; }
}
addEventListener('scroll', () => { if (!ticking) { ticking = true; requestAnimationFrame(() => { onScroll(); ticking = false; }); } }, { passive: true });
addEventListener('resize', onScroll);
if (tower && reduced) { renderTower(1); parts.items.forEach(el => el.classList.add('active')); }
if (steps && reduced) steps.style.setProperty('--p', 1);
onScroll();

